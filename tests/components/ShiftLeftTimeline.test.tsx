import React from "react";
import { fireEvent, render, screen, within } from "@testing-library/react";
import { describe, expect, it } from "vitest";

import ShiftLeftTimeline, { SHIFT_LEFT_ASSUMPTIONS } from "@/components/curriculum/f1/ShiftLeftTimeline";
import { BUGS, findPreset, lateStageNote, movedCaveat, placeBug, predictionFeedback, PUSH_FURTHER, runTimeline, summarizeRun, TIMELINE } from "@/lib/shift-left-model";

const label = (id: string) => TIMELINE.find((s) => s.id === id)!.label;

const lockIn = (stageId: string) => {
  // The prediction fieldset; each option's accessible name starts with its lane label.
  const prompt = screen.getByRole("group", { name: /where is/i });
  const target = within(prompt)
    .getAllByRole("radio")
    .find((r) => r.closest("label")?.textContent?.startsWith(label(stageId)));
  fireEvent.click(target!);
  fireEvent.click(screen.getByRole("button", { name: /lock in prediction/i }));
};

const result = () => screen.queryByTestId("shift-left-result");
const positions = () => within(screen.getByRole("list", { name: "Token positions" })).getAllByRole("listitem");
const sw = (name: RegExp) => screen.getByRole("switch", { name });

describe("ShiftLeftTimeline", () => {
  it("names itself, declares a conceptual illustration, and places no token before a prediction", () => {
    render(<ShiftLeftTimeline />);
    expect(screen.getByRole("region", { name: "Shift-left timeline" })).toBeInTheDocument();
    expect(screen.getByText("Conceptual illustration")).toBeInTheDocument();
    expect(result()).not.toBeInTheDocument();
    expect(screen.queryByRole("list", { name: "Token positions" })).not.toBeInTheDocument();
    expect(screen.getByTestId("token-tray")).toBeInTheDocument();
    // No placement sentence or kind cue is on screen before the reveal.
    for (const p of runTimeline(findPreset("shift-left").enabled)) expect(screen.queryByText(p.sentence)).not.toBeInTheDocument();
    expect(screen.queryByText(/earliest reliable catcher/)).not.toBeInTheDocument();
    for (const b of BUGS) expect(screen.queryByTestId(`token-${b.id}`)).not.toBeInTheDocument();
  });

  it("all on: a correct prediction for the latch reveals it in the RTL lane at ×10, first in the step-through", () => {
    render(<ShiftLeftTimeline />);
    lockIn("rtl");
    expect(screen.getByText(/^Correct\./)).toBeInTheDocument();
    const res = result()!;
    const status = within(res).getByRole("status");
    expect(status).toHaveTextContent(`Token 1 of 6: ${placeBug("latch-width", findPreset("shift-left").enabled).sentence}`);
    expect(within(screen.getByTestId("lane-rtl")).getByTestId("token-latch-width")).toHaveTextContent("×10");
    // Only the predicted token is placed at step 1; the others wait.
    expect(within(res).getByTestId("token-tray")).toBeInTheDocument();
    expect(positions().filter((li) => li.textContent?.includes("not placed yet"))).toHaveLength(5);
  });

  it("stepping places one token per step, and 'Place every token' shows the summary generated by the model", () => {
    render(<ShiftLeftTimeline preset="late-discovery" />);
    lockIn("after-tape-out");
    fireEvent.click(screen.getByRole("button", { name: "Next token" }));
    expect(within(result()!).getByRole("status")).toHaveTextContent("Token 2 of 6");
    expect(positions().filter((li) => li.textContent?.includes("not placed yet"))).toHaveLength(4);
    fireEvent.click(screen.getByRole("button", { name: "Place every token" }));
    expect(screen.queryByTestId("token-tray")).not.toBeInTheDocument();
    const lane = screen.getByTestId("lane-after-tape-out");
    for (const b of BUGS) expect(within(lane).getByTestId(`token-${b.id}`)).toHaveTextContent("×1,000 or more");
    expect(screen.getByText(summarizeRun(runTimeline([])).sentence)).toBeInTheDocument();
    expect(screen.getByText(lateStageNote([])!)).toBeInTheDocument();
  });

  it("schedule slipped: predicting the RTL lane explains that the switched-off catcher moves the bug right", () => {
    const enabled = findPreset("schedule-slipped").enabled;
    render(<ShiftLeftTimeline preset="schedule-slipped" />);
    expect(sw(/^Lint/)).toHaveAttribute("aria-checked", "false");
    expect(sw(/^Block-level simulation/)).toHaveAttribute("aria-checked", "false");
    lockIn("rtl");
    expect(screen.getByText(/^Not quite\./).parentElement).toHaveTextContent(predictionFeedback("block-functional", enabled, "rtl"));
    expect(within(screen.getByTestId("lane-integration")).getByTestId("token-block-functional")).toHaveTextContent("→ ×100");
    // The best case on the token, and the reveal's second half in the summary: some of these bugs pass tape-out.
    fireEvent.click(screen.getByRole("button", { name: "Place every token" }));
    const summary = screen.getByTestId("shift-left-summary");
    expect(summary).toHaveTextContent(summarizeRun(runTimeline(enabled)).sentence);
    expect(summary).toHaveTextContent("only the lab or a customer will hit go past the dashed tape-out line (×1,000 or more)");
    expect(summary).toHaveTextContent(PUSH_FURTHER);
  });

  it("the assumptions carry the moved-token caveat and say formal is not credited with one-block functional bugs", () => {
    expect(SHIFT_LEFT_ASSUMPTIONS.some((a) => a.includes(movedCaveat()))).toBe(true);
    expect(SHIFT_LEFT_ASSUMPTIONS.some((a) => a.includes("Formal on blocks is not credited with one-block functional bugs"))).toBe(true);
  });

  it("keeps keyboard focus in place: on the prediction feedback after locking in, on the summary after 'Place every token'", () => {
    render(<ShiftLeftTimeline preset="late-discovery" />);
    lockIn("after-tape-out");
    // The explanation is the first thing heard, and it sits before the run, so reading forward reaches the run.
    const feedback = document.activeElement as HTMLElement;
    expect(feedback).toHaveTextContent(/^Correct\./);
    expect(feedback).toHaveTextContent(predictionFeedback("spec-contradiction", [], "after-tape-out"));
    expect(feedback.compareDocumentPosition(result()!) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
    const place = screen.getByRole("button", { name: "Place every token" });
    place.focus();
    fireEvent.click(place);
    expect(screen.getByTestId("shift-left-summary")).toHaveFocus();
  });

  it("late stages still matter: every early activity on, yet the boot hang passes the tape-out line", () => {
    const enabled = findPreset("late-stages").enabled;
    render(<ShiftLeftTimeline preset="late-stages" />);
    lockIn("integration");
    expect(screen.getByText(/^Not quite\./)).toBeInTheDocument();
    expect(within(screen.getByTestId("lane-after-tape-out")).getByTestId("token-boot-hang")).toHaveTextContent("✕ ×1,000 or more");
    fireEvent.click(screen.getByRole("button", { name: "Place every token" }));
    expect(screen.getByText(lateStageNote(enabled)!)).toBeInTheDocument();
    expect(within(screen.getByTestId("lane-after-tape-out")).getByTestId("token-block-interaction")).toBeInTheDocument();
  });

  it("toggling an activity after a reveal starts a new run and hides the answer again", () => {
    render(<ShiftLeftTimeline />);
    lockIn("rtl");
    expect(result()).toBeInTheDocument();
    fireEvent.click(sw(/^Lint/));
    expect(sw(/^Lint/)).toHaveAttribute("aria-checked", "false");
    expect(result()).not.toBeInTheDocument();
    expect(screen.getByRole("button", { name: /lock in prediction/i })).toBeInTheDocument();
    expect(screen.getByText("Your own mix of activities.")).toBeInTheDocument();
    lockIn("integration");
    expect(screen.getByText(/^Correct\./)).toBeInTheDocument();
    expect(within(screen.getByTestId("lane-integration")).getByTestId("token-latch-width")).toHaveTextContent("×100");
  });

  it("choosing another bug resets the prediction and that bug is revealed first", () => {
    render(<ShiftLeftTimeline />);
    fireEvent.click(within(screen.getByRole("radiogroup", { name: "Bug to predict" })).getByRole("radio", { name: /Spec contradiction/ }));
    lockIn("spec");
    expect(within(result()!).getByRole("status")).toHaveTextContent(placeBug("spec-contradiction", findPreset("shift-left").enabled).sentence);
    expect(within(screen.getByTestId("lane-spec")).getByTestId("token-spec-contradiction")).toHaveTextContent("×1");
  });

  it("choosing another bug after a reveal hides the result and asks for a new prediction", () => {
    render(<ShiftLeftTimeline />);
    lockIn("rtl");
    expect(result()).toBeInTheDocument();
    fireEvent.click(within(screen.getByRole("radiogroup", { name: "Bug to predict" })).getByRole("radio", { name: /Boot or driver hang/ }));
    expect(result()).not.toBeInTheDocument();
    expect(screen.getByRole("button", { name: /lock in prediction/i })).toBeInTheDocument();
    expect(screen.queryByText(placeBug("boot-hang", findPreset("shift-left").enabled).sentence)).not.toBeInTheDocument();
  });

  it("choosing another preset after a reveal hides the result and asks for a new prediction", () => {
    render(<ShiftLeftTimeline />);
    lockIn("rtl");
    expect(result()).toBeInTheDocument();
    fireEvent.click(within(screen.getByRole("group", { name: "Presets" })).getByRole("button", { name: "Late stages still matter" }));
    expect(result()).not.toBeInTheDocument();
    expect(screen.getByRole("button", { name: /lock in prediction/i })).toBeInTheDocument();
    expect(screen.getByText(findPreset("late-stages").setup)).toBeInTheDocument();
  });

  it("presets are toggle buttons that set the switches; the timeline lists every activity's on/off state as text", () => {
    render(<ShiftLeftTimeline />);
    const presets = screen.getByRole("group", { name: "Presets" });
    fireEvent.click(within(presets).getByRole("button", { name: "Everything off" }));
    expect(within(presets).getByRole("button", { name: "Everything off" })).toHaveAttribute("aria-pressed", "true");
    for (const s of screen.getAllByRole("switch")) expect(s).toHaveAttribute("aria-checked", "false");
    expect(within(screen.getByRole("list", { name: "Activities while the RTL is written" })).getByText("Lint").parentElement).toHaveTextContent("Lint (off)");
  });

  it("revealing without predicting still runs the model", () => {
    render(<ShiftLeftTimeline preset="late-stages" />);
    fireEvent.click(screen.getByRole("button", { name: /reveal without predicting/i }));
    expect(within(result()!).getByRole("status")).toHaveTextContent(placeBug("boot-hang", findPreset("late-stages").enabled).sentence);
  });
  it("revealing without predicting moves focus to the explanation, not to <body>", () => {
    render(<ShiftLeftTimeline preset="late-stages" />);
    const skip = screen.getByRole("button", { name: /reveal without predicting/i });
    skip.focus();
    fireEvent.click(skip);
    expect(document.activeElement).not.toBe(document.body);
    expect(document.activeElement).toHaveTextContent(placeBug("boot-hang", findPreset("late-stages").enabled).sentence);
  });

  it("schedule slipped: predicting past tape-out is told it is partly right, with the caveat, and never 'never see it'", () => {
    const enabled = findPreset("schedule-slipped").enabled;
    render(<ShiftLeftTimeline preset="schedule-slipped" />);
    lockIn("after-tape-out");
    const fb = screen.getByText(/^Not quite\./).parentElement!;
    expect(fb).toHaveTextContent(predictionFeedback("block-functional", enabled, "after-tape-out"));
    expect(fb).toHaveTextContent(movedCaveat());
    expect(fb).not.toHaveTextContent("never see it");
  });

  it("section captions are headings, so screen-reader users can jump between them", () => {
    render(<ShiftLeftTimeline />);
    const names = screen.getAllByRole("heading", { level: 4 }).map((h) => h.textContent);
    expect(names).toEqual(["Presets", "Activities before tape-out", "Bug to predict"]);
    // The presets group takes its name from its heading.
    const presets = screen.getByRole("group", { name: "Presets" });
    expect(presets).toHaveAttribute("aria-labelledby", screen.getByRole("heading", { name: "Presets" }).id);
  });
});
