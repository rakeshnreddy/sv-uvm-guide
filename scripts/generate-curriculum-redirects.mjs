#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "..");
const manifestPath = path.join(repositoryRoot, "content/curriculum/redirects.json");
const generatedPath = path.join(repositoryRoot, "src/generated/curriculum-redirects.mjs");
const checkOnly = process.argv.includes("--check");

function hasWildcard(value) {
  return value.includes(":") || value.includes("(");
}

function specificity(source) {
  const exactBonus = hasWildcard(source) ? 0 : 10_000;
  const staticSegments = source
    .split("/")
    .filter(Boolean)
    .filter((segment) => !segment.includes(":") && !segment.includes("("))
    .length;
  return exactBonus + staticSegments * 100 + source.length;
}

export function sortCurriculumRedirects(redirects) {
  return [...redirects].sort(
    (left, right) =>
      specificity(right.source) - specificity(left.source) ||
      left.source.localeCompare(right.source),
  );
}

function destinationExists(destination) {
  if (!destination.startsWith("/curriculum/")) return true;

  const clean = destination
    .replace(/\/:slug\*$/, "")
    .replace(/\(\/:slug\*\)$/, "")
    .split("?")[0];
  const segments = clean.split("/").filter(Boolean).slice(1);
  const base = path.join(repositoryRoot, "content/curriculum", ...segments);
  return fs.existsSync(`${base}.mdx`) || fs.existsSync(path.join(base, "index.mdx"));
}

export function validateCurriculumRedirects(redirects) {
  const errors = [];
  const sources = new Set();

  redirects.forEach((redirect, index) => {
    if (
      !redirect ||
      typeof redirect.source !== "string" ||
      typeof redirect.destination !== "string" ||
      typeof redirect.permanent !== "boolean"
    ) {
      errors.push(`redirect ${index} has an invalid shape`);
      return;
    }

    if (sources.has(redirect.source)) {
      errors.push(`duplicate redirect source: ${redirect.source}`);
    }
    sources.add(redirect.source);

    if (redirect.source === redirect.destination) {
      errors.push(`self redirect: ${redirect.source}`);
    }
    if (!destinationExists(redirect.destination)) {
      errors.push(`missing redirect destination: ${redirect.destination}`);
    }
  });

  const exactRedirects = new Map(
    redirects
      .filter(({ source, destination }) => !hasWildcard(source) && !hasWildcard(destination))
      .map(({ source, destination }) => [source, destination]),
  );

  exactRedirects.forEach((_destination, source) => {
    const visited = new Set([source]);
    let current = source;
    while (exactRedirects.has(current)) {
      current = exactRedirects.get(current);
      if (visited.has(current)) {
        errors.push(`redirect loop detected from ${source}`);
        break;
      }
      visited.add(current);
    }
  });

  return errors;
}

const redirects = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const errors = validateCurriculumRedirects(redirects);
if (errors.length > 0) {
  console.error(errors.map((error) => `- ${error}`).join("\n"));
  process.exit(1);
}

const sorted = sortCurriculumRedirects(redirects);
const generated = `// Generated by scripts/generate-curriculum-redirects.mjs. Do not edit.\nexport const curriculumRedirects = ${JSON.stringify(sorted, null, 2)};\n`;

if (checkOnly) {
  if (!fs.existsSync(generatedPath) || fs.readFileSync(generatedPath, "utf8") !== generated) {
    console.error("Generated curriculum redirects are stale. Run node scripts/generate-curriculum-redirects.mjs.");
    process.exit(1);
  }
  console.log(`Validated ${sorted.length} curriculum redirects.`);
} else {
  fs.mkdirSync(path.dirname(generatedPath), { recursive: true });
  fs.writeFileSync(generatedPath, generated);
  console.log(`Generated ${sorted.length} curriculum redirects.`);
}
