import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { z } from "zod";

const repositoryRoot = process.cwd();
const labsRoot = path.join(repositoryRoot, "content", "curriculum", "labs");
const outputPath = path.join(repositoryRoot, "src", "generated", "lab-registry.ts");
const knownGraders = new Set(["sv-basics-v1"]);

const assetSchema = z.object({
  path: z.string().min(1),
  role: z.enum(["guide", "starter", "reference", "solution"]),
  language: z.string().min(1),
  editable: z.boolean(),
}).strict();
const stepSchema = z.object({
  id: z.string().regex(/^[a-zA-Z0-9_-]+$/),
  version: z.string().min(1),
  completion: z.enum(["graded", "self_attested"]),
  title: z.string().min(1),
  instructions: z.string().min(1),
  starterCode: z.string(),
}).strict();
const manifestSchema = z.object({
  id: z.string().regex(/^[a-z0-9-]+$/),
  version: z.string().min(1),
  title: z.string().min(1),
  description: z.string().min(1),
  owningModule: z.string().min(1),
  routeSlug: z.string().regex(/^[a-z0-9-]+$/),
  moduleHref: z.string().startsWith("/curriculum/").optional(),
  status: z.enum(["available", "coming_soon", "archived"]),
  graderId: z.string().regex(/^[a-z0-9-]+$/).optional(),
  labPrerequisites: z.array(z.string().regex(/^[a-z0-9-]+$/)),
  modulePrerequisites: z.array(z.string().min(1)),
  steps: z.array(stepSchema),
  assets: z.array(assetSchema),
}).strict();

function walk(directory, fileName) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const candidate = path.join(directory, entry.name);
    if (entry.isDirectory()) return walk(candidate, fileName);
    return entry.isFile() && entry.name === fileName ? [candidate] : [];
  });
}

const curriculumDataSource = fs.readFileSync(
  path.join(repositoryRoot, "src", "lib", "curriculum-data.tsx"),
  "utf8",
);
const curriculumSlugs = new Set(
  [...curriculumDataSource.matchAll(/"slug":\s*"([^"]+)"/g)].map((match) => match[1]),
);
const manifestFiles = walk(labsRoot, "lab.json").sort();
const records = manifestFiles.map((manifestPath) => {
  const parsed = manifestSchema.parse(JSON.parse(fs.readFileSync(manifestPath, "utf8")));
  const labDirectory = path.dirname(manifestPath);
  const relativeDirectory = path.relative(repositoryRoot, labDirectory).split(path.sep).join("/");

  const stepIds = parsed.steps.map((step) => step.id);
  if (new Set(stepIds).size !== stepIds.length) throw new Error(`${parsed.id}: duplicate step id`);
  const assetPaths = parsed.assets.map((asset) => asset.path);
  if (new Set(assetPaths).size !== assetPaths.length) throw new Error(`${parsed.id}: duplicate asset path`);

  for (const asset of parsed.assets) {
    if (asset.path.startsWith("/") || asset.path.split("/").includes("..")) {
      throw new Error(`${parsed.id}: asset escapes lab directory: ${asset.path}`);
    }
    if (asset.editable && asset.role !== "starter") {
      throw new Error(`${parsed.id}: only starter assets may be editable: ${asset.path}`);
    }
    const resolvedAsset = path.resolve(labDirectory, asset.path);
    if (!resolvedAsset.startsWith(`${labDirectory}${path.sep}`) || !fs.existsSync(resolvedAsset) || !fs.statSync(resolvedAsset).isFile()) {
      throw new Error(`${parsed.id}: missing asset: ${asset.path}`);
    }
  }

  const ownsKnownModule = [...curriculumSlugs].some(
    (slug) => slug === parsed.owningModule || slug.startsWith(parsed.owningModule),
  );
  if (!ownsKnownModule) throw new Error(`${parsed.id}: unknown owning module ${parsed.owningModule}`);
  if (parsed.graderId && !knownGraders.has(parsed.graderId)) {
    throw new Error(`${parsed.id}: unknown grader ${parsed.graderId}`);
  }
  const gradedSteps = parsed.steps.filter((step) => step.completion === "graded");
  if (gradedSteps.length > 0 && !parsed.graderId) {
    throw new Error(`${parsed.id}: graded steps require a manifest-owned grader`);
  }

  return { ...parsed, assetLocation: relativeDirectory };
});

const ids = new Set(records.map((lab) => lab.id));
if (ids.size !== records.length) throw new Error("Duplicate lab IDs detected");
if (new Set(records.map((lab) => lab.routeSlug)).size !== records.length) {
  throw new Error("Duplicate lab route slugs detected");
}
for (const lab of records) {
  for (const prerequisite of lab.labPrerequisites) {
    if (!ids.has(prerequisite)) throw new Error(`${lab.id}: unknown lab prerequisite ${prerequisite}`);
  }
}

const generated = `// Generated by scripts/generate-lab-registry.mjs. Do not edit manually.\n` +
  `import type { LabManifest } from "@/lib/lab-manifest";\n\n` +
  `export const GENERATED_LAB_MANIFESTS = ${JSON.stringify(records, null, 2)} satisfies LabManifest[];\n`;

if (process.argv.includes("--check")) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== generated) {
    console.error("Generated lab registry is stale. Run: node scripts/generate-lab-registry.mjs");
    process.exit(1);
  }
  console.log(`Validated ${records.length} lab manifests.`);
} else if (process.argv.includes("--stdout")) {
  process.stdout.write(generated);
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, generated);
  console.log(`Generated ${records.length} lab manifests.`);
}
