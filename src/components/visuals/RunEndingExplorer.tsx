const toPrediction = (options: GradedOption[]) => options.map((o) => ({ id: o.id, label: o.label, correct: o.correct, feedback: o.feedback }));

interface TraceBodyProps {
  result: SimResult;
  prepared: PreparedScenario;
  playback: PlaybackApi;
  lines: CodeTraceLine[];
  watch: string[];
  onReveal: (revealed: boolean) => void;
  /** Extra text for the last step, generated by the model. */
  closing?: string;
}

/** The revealed part of a lanes view: narration, transport, lanes, process table, counters, output and ending. */
function TraceBody({ result, prepared, playback, lines, watch, onReveal, closing }: TraceBodyProps) {
  const last = result.trace.length - 1;
  const index = Math.min(playback.index, last);
  const step = result.trace[index];
  const previous = index > 0 ? result.trace[index - 1] : undefined;
  return (
    <div className="space-y-4">
      <RevealSignal onReveal={onReveal} />
      <RunNarration step={step} result={result} />
      <PlaybackControls playback={playback} stepCount={result.trace.length} stepNoun="Run step" describeStep={(i) => result.trace[i]?.what ?? ""} />
      <ProcessLanes result={result} index={index} />
      <div className="grid items-start gap-4 grid-cols-[repeat(auto-fit,minmax(min(100%,280px),1fr))]">
        <ThreadTable step={step} lines={lines} />
        <div className="min-w-0 space-y-3">
          <div>
            <p className="mb-2 text-[11px] font-semibold uppercase tracking-[0.18em] text-muted-foreground">Counters after this step</p>
            <div className="flex flex-wrap gap-2">
              {watch.map((name) => (
                <ValueChip key={name} name={name} value={formatVal(step.vars[name])} changed={previous !== undefined && previous.vars[name] !== step.vars[name]} />
              ))}
            </div>
          </div>
          <RunLog step={step} result={result} prepared={prepared} index={index} />
        </div>
      </div>
      {index === last ? (
        <>
          <EndingPanel result={result} />
          {closing ? <p className="text-sm text-muted-foreground">{closing}</p> : null}
        </>
      ) : (
        <p className="text-xs text-muted-foreground">Step to the end to see how the run ends.</p>
      )}
    </div>
  );
}

function useCode(prepared: PreparedScenario) {
  return useMemo(() => codeLines(lessonSource(prepared)), [prepared]);
}

/* ------------------------------------------------------------------------- */
/* severity-and-end                                                           */
/* ------------------------------------------------------------------------- */

function SeverityAndEnd() {
  const [control, setControl] = useState<EndControl>("error");
  const [count, setCount] = useState(true);
  const run = useMemo(() => runSeverity({ control, count }), [control, count]);
  const key = `${control}:${count}`;
  const lines = useCode(run.prepared);
  const playback = usePlayback(run.result.trace.length, key);
  const [revealed, setRevealed] = useState(false);
  const step = run.result.trace[Math.min(playback.index, run.result.trace.length - 1)];
  const ctlKey = run.prepared.lineKeyOf.get("ctl");

  const renderLineControl = (line: CodeTraceLine) => {
    if (!line.key || line.key !== ctlKey) return null;
    return (
      <span className="flex max-w-[11rem] flex-wrap items-center justify-end gap-1 font-sans">
        <label className="flex items-center gap-1 text-[11px] text-slate-300">
          <span className="sr-only">Statement at t = {run.controlTime} ns</span>
          <select
            value={control}
            onChange={(e) => setControl(e.target.value as EndControl)}
            className="h-8 rounded-md border border-slate-500 bg-slate-900 px-1 text-[12px] text-slate-100 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-cyan-300"
          >
            {END_CONTROLS.map((c) => (
              <option key={c} value={c}>
                {CONTROL_FACTS[c].label}
              </option>
            ))}
          </select>
        </label>
        <label className="flex min-h-8 items-center gap-1 text-[11px] text-slate-300">
          <input type="checkbox" checked={count} onChange={(e) => setCount(e.target.checked)} className="h-4 w-4 accent-cyan-400" />
          n_fail++ in the failing branch
        </label>
      </span>
    );
  };

  return (
    <VisualFrame
      label="Run ending explorer: severity tasks and the end of the run"
      eyebrow="Experiment · predict then reveal"
      title="Report, end, or suspend?"
      summary={`Pick the statement that runs at t = ${run.controlTime} ns and whether the failing branch counts. Predict what still prints and what the summary says, then step through each call and see whether it returns (IEEE 1800-2023 §20.2, §20.10, §9.2.3).`}
      fidelity="model"
      assumptions={RUN_ENDING_ASSUMPTIONS}
    >
      <CodeTrace
        label={`Code under simulation · the statement at t = ${run.controlTime} ns is yours to pick`}
        lines={lines}
        activeKey={revealed ? step.lineKey : undefined}
        renderLineControl={renderLineControl}
      />
      <PredictionPrompt resetKey={key} question={`Which later lines appear in the output?`} options={toPrediction(severityLineOptions(run))}>
        <PredictionPrompt resetKey={key} question="What does the summary print?" options={toPrediction(severityCountOptions(run))}>
          <TraceBody
            result={run.result}
            prepared={run.prepared}
            playback={playback}
            lines={lines}
            watch={["n_fail"]}
            onReveal={setRevealed}
            closing={counterExplanation(run)}
          />
        </PredictionPrompt>
      </PredictionPrompt>
    </VisualFrame>
  );
}

