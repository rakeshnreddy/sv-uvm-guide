/* watchdog-race                                                              */
/* ------------------------------------------------------------------------- */

function WatchdogRace() {
  const [variant, setVariant] = useState<EndOfRunVariant>("normal");
  const run = useMemo(() => runEndOfRun(variant), [variant]);
  const lines = useCode(run.prepared);
  const playback = usePlayback(run.result.trace.length, variant);
  const [revealed, setRevealed] = useState(false);
  const step = run.result.trace[Math.min(playback.index, run.result.trace.length - 1)];

  return (
    <VisualFrame
      label="Run ending explorer: the watchdog race"
      eyebrow="Experiment · predict then reveal"
      title="The watchdog race: does a verdict print?"
      summary="The end of the lesson's main initial block: fork run and watchdog, join_any, disable fork, report(), $finish. Pick how the run goes, predict whether the summary prints and what ends the run, then step through the lanes (IEEE 1800-2023 §9.3.2, §9.6.3, §20.10, §4.5)."
      fidelity="model"
      assumptions={[
        ...RUN_ENDING_ASSUMPTIONS,
        "Stand-ins: n_exp stands in for exp_q.size(), because the model has no queue expression; reset_dut() and drain() keep only their waits; report() is a task here and a void function in the lesson; %0t prints the raw time.",
      ]}
    >
      <SegmentedControl label="How the run goes" options={END_OF_RUN_VARIANTS} value={variant} onChange={setVariant} />
      <p className="text-xs text-muted-foreground">n_exp stands in for exp_q.size(): the model has no queue expression.</p>
      <CodeTrace label="tb_top: the end of the main initial block" lines={lines} activeKey={revealed ? step.lineKey : undefined} />
      <PredictionPrompt resetKey={variant} question="Does the summary line print, and which statement ends the run?" options={toPrediction(endOfRunOptions(run))}>
        <TraceBody result={run.result} prepared={run.prepared} playback={playback} lines={lines} watch={["pass_cnt", "fail_cnt", "n_exp"]} onReveal={setRevealed} />
      </PredictionPrompt>
    </VisualFrame>
  );
}

