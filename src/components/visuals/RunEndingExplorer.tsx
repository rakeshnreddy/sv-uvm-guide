/* Entry                                                                      */
/* ------------------------------------------------------------------------- */

export interface RunEndingExplorerProps {
  /** "lanes": process lanes on a time axis; "loop": the §4.5 flowchart. The preset decides when they disagree. */
  view?: RunEndingView;
  preset?: RunEndingPreset;
}

/** How a run ends and how simulation time advances, on the tested process model. */
export default function RunEndingExplorer({ view, preset = "severity-and-end" }: RunEndingExplorerProps) {
  const shown: RunEndingView = PRESET_VIEW[preset] ?? view ?? "lanes";
  if (shown === "loop") return <SchedulerLoopView />;
  return preset === "watchdog-race" ? <WatchdogRace /> : <SeverityAndEnd />;
}
