const STATUS_TEXT: Record<PlacementResult["status"], { mark: string; text: string; className: string }> = {
  correct: { mark: "✓", text: "right", className: "text-success" },
  partial: { mark: "◐", text: "partly right", className: "text-foreground" },
  wrong: { mark: "✕", text: "not quite", className: "text-danger" },
};

type RungState = "idle" | "placed" | "hit" | "missed" | "extra" | "clear";

/** Per-place marker after a check: a label and a shape, on the neutral surface (no signal colours). */
function rungState(place: SorterPlace, picked: SorterPlace[], result?: PlacementResult): RungState {
  if (!result) return picked.includes(place) ? "placed" : "idle";
  if (result.hits.includes(place)) return "hit";
  if (result.missed.includes(place)) return "missed";
  if (result.extra.includes(place)) return "extra";
  return "clear";
}

const RUNG_MARK: Record<Exclude<RungState, "idle" | "clear">, { mark: string; text: string; className: string }> = {
  placed: { mark: "●", text: "placed", className: "text-foreground" },
  hit: { mark: "✓", text: "lands here", className: "text-success" },
  missed: { mark: "○", text: "missed: lands here", className: "text-foreground" },
  extra: { mark: "✕", text: "not here", className: "text-danger" },
};

function SorterRung({
  place,
  state,
  checked,
  onToggle,
  hint,
}: {
  place: SorterPlace;
  state: RungState;
  checked: boolean;
  onToggle: () => void;
  hint: string;
}) {
  const mark = state === "idle" || state === "clear" ? null : RUNG_MARK[state];
  return (
    <button
      type="button"
      aria-pressed={state === "placed" || state === "hit" || state === "extra"}
      disabled={checked}
      onClick={onToggle}
      className={cn(
        "flex min-h-10 w-full items-center justify-between gap-3 rounded-lg border bg-card px-3 py-2 text-left transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring disabled:cursor-default motion-reduce:transition-none",
        state === "placed" ? "border-border border-l-2 border-l-primary bg-muted" : "border-border",
        state === "missed" && "border-dashed border-foreground/60",
        !checked && "hover:bg-muted",
        state === "clear" && "opacity-60",
      )}
    >
      <span className="min-w-0">
        <span className="text-sm font-medium text-foreground">{PLACE_LABELS[place]}</span>
        <span className="ml-2 text-xs text-muted-foreground">{hint}</span>
      </span>
      {mark ? (
        <span className={cn("shrink-0 text-xs font-medium", mark.className)}>
          <span aria-hidden>{mark.mark} </span>
          {mark.text}
        </span>
      ) : null}
    </button>
  );
}

/** What a wrongly chosen place holds, so the reveal names the misconception (shown only after a check). */
