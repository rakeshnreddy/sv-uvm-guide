function RegionSorter({ items, allowMulti }: { items: SorterItems | string; allowMulti: boolean | string }) {
  const deck = useMemo(() => resolveSorterDeck(items, allowMulti), [items, allowMulti]);
  const cards = deck.cards;
  const [index, setIndex] = useState(0);
  const [picks, setPicks] = useState<Record<string, SorterPlace[]>>({});
  const [results, setResults] = useState<Record<string, PlacementResult>>({});
  const [finished, setFinished] = useState(false);
  const [announcement, setAnnouncement] = useState("");
  const cardRef = useRef<HTMLDivElement>(null);
  const revealRef = useRef<HTMLDivElement>(null);
  const summaryRef = useRef<HTMLParagraphElement>(null);
  /** Where focus goes after the next render, so it never falls to <body> when the focused control unmounts. */
  const pendingFocus = useRef<"card" | "reveal" | "summary" | null>(null);

  const card = cards[index];
  const picked = card ? (picks[card.id] ?? []) : [];
  const result = card ? results[card.id] : undefined;
  const labels = cards.map((c) => cardLabel(c, cards));
  const cardName = (i: number) => `Card ${i + 1} of ${cards.length}: ${labels[i]}, ${cards[i].context}. ${cards[i].ask}`;

  useEffect(() => {
    const target = pendingFocus.current;
    if (!target) return;
    pendingFocus.current = null;
    (target === "card" ? cardRef : target === "reveal" ? revealRef : summaryRef).current?.focus();
  });

  const toggle = (place: SorterPlace) => {
    if (!card || result) return;
    const next = togglePlace(picked, place, deck.allowMulti);
    setPicks((p) => ({ ...p, [card.id]: next }));
    setAnnouncement(placementAnnouncement(card, next));
  };

  const check = () => {
    if (!card || picked.length === 0) return;
    const graded = gradePlacement(card, picked);
    setResults((r) => ({ ...r, [card.id]: graded }));
    // Focus moves to the reveal, which is named by the verdict; announcing it here too would read it twice.
    setAnnouncement("");
    pendingFocus.current = "reveal";
  };

  /** Opens card i. A pick from the phone select keeps focus on the select (arrow keys can fire change) and announces the card instead. */
  const goTo = (i: number, moveFocus = true) => {
    if (moveFocus) pendingFocus.current = "card";
    else if (cards[i]) setAnnouncement(cardName(i));
    setFinished(false);
    setIndex(i);
  };

  const next = () => {
    const open = cards.findIndex((c, i) => i > index && !results[c.id]);
    const anyOpen = open >= 0 ? open : cards.findIndex((c) => !results[c.id]);
    if (anyOpen >= 0) goTo(anyOpen);
    else {
      pendingFocus.current = "summary";
      setFinished(true);
    }
  };

  const restart = () => {
    setPicks({});
    setResults({});
    setFinished(false);
    setAnnouncement("");
    pendingFocus.current = "card";
    setIndex(0);
  };

  const checkedCount = cards.filter((c) => results[c.id]).length;
  const ladder = REGION_ORDER;
  const fidelity = deckFidelity(cards);
  const referenceCount = cards.filter((c) => c.fidelity === "reference").length;
  const statusOf = (c: SorterCard) => (results[c.id] ? STATUS_TEXT[results[c.id].status] : null);

  return (
    <VisualFrame
      label="Region sorter"
      eyebrow="Retrieval practice"
      title="Place each construct in its region"
      summary={`${
        deck.allowMulti
          ? `${cards.length} cards. Place each one on every region where one of its events lands, or in the no-region tray, then check.`
          : `${cards.length} cards. Place each one on the region where it lands, or in the no-region tray, then check.`
      }${
        referenceCount > 0
          ? ` ${referenceCount} of ${cards.length} ${referenceCount === 1 ? "is a reference card" : "are reference cards"}, read from the clause and not simulated; the rest are read from a model run.`
          : ""
      }`}
      fidelity={fidelity}
      assumptions={SORTER_ASSUMPTIONS}
    >
      <p role="status" aria-live="polite" className="sr-only">
        {announcement}
      </p>
      {deck.unknownIds.length > 0 ? (
        <p className="rounded-lg border border-border bg-card p-2 text-xs text-muted-foreground">
          Not in the deck (no card has this id): <span className={codeChip}>{deck.unknownIds.join(", ")}</span>
        </p>
      ) : null}
      {deck.omittedMulti.length > 0 ? (
        <p className="rounded-lg border border-border bg-card p-2 text-xs text-muted-foreground">
          This deck takes one region per card, so the cards that land in several are left out:{" "}
          <span className={codeChip}>{deck.omittedMulti.map((c) => c.code).join("  ")}</span>
        </p>
      ) : null}

      {cards.length === 0 ? (
        <p className="text-sm text-muted-foreground">This deck has no cards.</p>
      ) : (
        <>
          <div>
            <p className="mb-1 text-xs font-medium text-muted-foreground">
              Cards: {checkedCount} of {cards.length} checked
            </p>
            <label className="block sm:hidden">
              <span className="sr-only">Go to card</span>
              <select
                value={finished ? "" : String(index)}
                onChange={(e) => {
                  if (e.target.value !== "") goTo(Number(e.target.value), false);
                }}
                className="min-h-10 w-full rounded-lg border border-border bg-card px-2.5 py-1 text-sm text-foreground focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
              >
                {finished ? <option value="">Results</option> : null}
                {cards.map((c, i) => {
                  const status = statusOf(c);
                  return (
                    <option key={c.id} value={String(i)}>
                      {`Card ${i + 1} of ${cards.length}: ${labels[i]}${status ? `, ${status.text}` : ""}`}
                    </option>
                  );
                })}
              </select>
            </label>
            <ol aria-label="Cards" className="hidden flex-wrap gap-2 sm:flex">
              {cards.map((c, i) => {
                const status = statusOf(c);
                const current = !finished && i === index;
                return (
                  <li key={c.id}>
                    <button
                      type="button"
                      aria-current={current ? "true" : undefined}
                      aria-label={`Card ${i + 1}: ${labels[i]}${status ? `, ${status.text}` : ""}`}
                      onClick={() => goTo(i)}
                      className={cn(
                        "inline-flex min-h-10 max-w-full items-center gap-1.5 rounded-lg border border-border bg-card px-2.5 py-1 text-xs text-foreground transition-colors hover:bg-muted focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring motion-reduce:transition-none",
                        current && "border-l-2 border-l-primary bg-muted",
                      )}
                    >
                      <span className={cn(codeChip, "truncate")}>{labels[i]}</span>
                      {status ? (
                        <span aria-hidden className={status.className}>
                          {status.mark}
                        </span>
                      ) : null}
                    </button>
                  </li>
                );
              })}
            </ol>
          </div>

          {finished ? (
            <div className="space-y-3 rounded-xl border border-border bg-card p-3">
              <p ref={summaryRef} tabIndex={-1} className="text-sm font-semibold text-foreground focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring">
                {sorterSummary(cards.map((c) => results[c.id]).filter(Boolean), cards.length)}
              </p>
              <ol className="space-y-1 text-sm" aria-label="Your placements">
                {cards.map((c, i) => {
                  const r = results[c.id];
                  return (
                    <li key={c.id} className="flex gap-2">
                      <span aria-hidden className={r ? STATUS_TEXT[r.status].className : "text-muted-foreground"}>
                        {r ? STATUS_TEXT[r.status].mark : "–"}
                      </span>
                      <span className="min-w-0 break-words">
                        <span className="sr-only">{r ? `${STATUS_TEXT[r.status].text}: ` : "not checked: "}</span>
                        <code className={cn(codeChip, "rounded bg-muted px-1")}>{labels[i]}</code> → {whereText(c)}
                      </span>
                    </li>
                  );
                })}
              </ol>
              <button type="button" onClick={restart} className={sorterButton}>
                Sort the cards again
              </button>
            </div>
          ) : card ? (
            <div className="space-y-3">
              <div
                ref={cardRef}
                tabIndex={-1}
                role="group"
                aria-label={cardName(index)}
                className="space-y-2 rounded-xl border border-border bg-card p-3 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
              >
                <p className="text-xs text-muted-foreground">
                  Card {index + 1} of {cards.length}
                </p>
                <pre className="overflow-x-auto whitespace-pre-wrap break-words rounded-lg border border-code-border bg-code-surface px-3 py-2 text-sm text-code-foreground">
                  <code className={codeChip}>{card.code}</code>
                </pre>
                <p className="text-xs text-muted-foreground">{card.context}</p>
                <p className="text-sm font-semibold text-foreground">{card.ask}</p>
                <p className="text-xs text-muted-foreground">
                  {deck.allowMulti ? "Choose every region that applies. Choosing a region again removes it." : "Choose one region."}
                </p>
              </div>

              <div role="group" aria-label="Regions of a time slot, in order" className="grid gap-1.5">
                {ladder.map((region) => (
                  <SorterRung
                    key={region}
                    place={region}
                    hint={`${setLabel(region)} · ${REGION_CLAUSES[region]}`}
                    state={rungState(region, picked, result)}
                    checked={Boolean(result)}
                    onToggle={() => toggle(region)}
                  />
                ))}
              </div>
              <div role="group" aria-label="Not on the ladder" className="rounded-lg border border-dashed border-border p-1.5">
                <SorterRung place="none" hint="tray: not a region of the ladder" state={rungState("none", picked, result)} checked={Boolean(result)} onToggle={() => toggle("none")} />
              </div>

              {result ? <SorterReveal card={card} result={result} focusRef={revealRef} /> : null}

              <div className="flex flex-wrap gap-2">
                {!result ? (
                  <>
                    <button type="button" onClick={check} disabled={picked.length === 0} className={sorterPrimaryButton}>
                      Check placement
                    </button>
                    <button
                      type="button"
                      onClick={() => {
                        setPicks((p) => ({ ...p, [card.id]: [] }));
                        setAnnouncement(placementAnnouncement(card, []));
                      }}
                      disabled={picked.length === 0}
                      className={sorterButton}
                    >
                      Clear
                    </button>
                  </>
                ) : (
                  <button type="button" onClick={next} className={sorterButton}>
                    {checkedCount < cards.length ? "Next card" : "See results"}
                  </button>
                )}
              </div>

            </div>
          ) : null}
        </>
      )}
    </VisualFrame>
  );
}
