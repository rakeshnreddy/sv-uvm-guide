/**
 * Region set of each rung, a text cue and never a colour. §4.4.1 defines only
 * the active region set (Active, Inactive, NBA) and the reactive region set
 * (Reactive, Re-Inactive, Re-NBA); Preponed, Observed and Postponed are in
 * neither. Postponed adds "read-only": §4.4.2.9 makes writing to any net or
 * variable illegal there. §4.4.2.1 does not call Preponed read-only.
 */
function setLabel(region: RegionId): string {
  const family = regionGuideById[region].family;
  if (family === "activeSet") return "active set";
  if (family === "reactiveSet") return "reactive set";
  return region === "postponed" ? "in neither set · read-only" : "in neither set";
}

