/**
 * Key terms for the concept map (/knowledge-hub) and for ConceptLink /
 * ConceptModal in lessons that opt in with `conceptLinking: true`.
 *
 * Where the terms come from:
 * - the canonical terminology table, docs/curriculum-quality/curriculum-spine.md §5.1
 *   (`source: 'spine §5.1'`), using the spelling that table prescribes;
 * - the "Must cover" lists of the module intent cards in the same file, §2 and §4.2
 *   (`source: 'intent card <code>'`).
 *
 * `taughtIn` names the lessons ("<ModuleFolder>/<lesson>") that teach the term,
 * the introducing lesson first. tests/lib/knowledge-graph-engine.test.ts checks
 * that every lesson exists in the curriculum manifest and that its MDX uses the
 * term's name or one of its aliases, so a renamed lesson or a dropped section
 * fails the build instead of leaving a dead concept link.
 *
 * A term's tier is not stored: the graph derives it from the tier of the
 * earliest lesson that teaches it.
 */

export interface ConceptTerm {
  /** Kebab-case; the graph id is `term:<slug>`. */
  slug: string;
  /** The canonical spelling (spine §5.1). Lesson prose matching this name gets a concept link. */
  name: string;
  /** Other spellings for search; also accepted by the lesson-content check. */
  aliases?: readonly string[];
  /** One or two sentences in plain words. */
  description: string;
  /** Lesson keys, introducing lesson first. */
  taughtIn: readonly string[];
  /** Slugs of closely related terms. */
  related?: readonly string[];
  source: string;
}

